def main():
    # Old backends silently drop the `ky` field; make sure this one knows it.
    tests = call("GET", "/tests")
    if tests and "kind" not in tests[0]:
        sys.exit("Бэкенд ещё старый (нет поддержки переводов). Сначала задеплойте новую версию.")

    token = call("POST", "/auth/login", {
        "email": os.environ.get("ADMIN_EMAIL", "admin@mdn.kg"),
        "password": os.environ.get("ADMIN_PASSWORD", "admin123"),
    })["token"]

    done = set()
    for n in call("GET", "/admin/news", token=token):
        tr = NEWS_KY.get(n["title"])
        if not tr:
            print("no translation:", n["title"])
            continue
        n["ky"] = tr
        call("PUT", f"/admin/news/{n['id']}", n, token)
        done.add(n["title"])
        print("ky:", tr["title"])
    for title in NEWS_KY.keys() - done:
        print("not on the site:", title)
    print(f"translated {len(done)} of {len(NEWS_KY)}")


if __name__ == "__main__":
    main()
