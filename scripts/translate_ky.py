"""Adds Kyrgyz translations to the seeded news (matched by the Russian title).

    python3 scripts/translate_ky.py [BASE_URL]      # default http://localhost:8080

Uses ADMIN_EMAIL / ADMIN_PASSWORD from the environment. Safe to run again:
it only rewrites the `ky` block of matching articles and leaves everything else as is.
Refuses to run against a backend that does not support translations yet.
"""
import json
import os
import sys
import urllib.error
import urllib.request

BASE = (sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8080").rstrip("/") + "/api"


def call(method, path, body=None, token=None):
    headers = {"Content-Type": "application/json", "User-Agent": "mdn-seed/1.0"}
    if token:
        headers["Authorization"] = "Bearer " + token
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(BASE + path, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            raw = r.read()
            return json.loads(raw) if raw else None
    except urllib.error.HTTPError as e:
        sys.exit(f"{method} {path}: {e.code} {e.read().decode()}")


def ky(title, summary, *lines):
    return {"title": title, "summary": summary, "body": "\n".join(lines)}


