def main():
    env = load_env()
    email, password = env.get("ADMIN_EMAIL", "admin@mdn.kg"), env.get("ADMIN_PASSWORD", "admin123")
    token = call("POST", "/auth/login", {"email": email, "password": password})["token"]

    existing = {n["title"] for n in call("GET", "/admin/news", token=token)}
    # Oldest first, so the featured launch post ends up on top by date as well.
    for n in reversed(NEWS):
        if n["title"] in existing:
            print("skip news:", n["title"])
            continue
        call("POST", "/admin/news", {"published": True, "featured": False, **n}, token)
        print("news:", n["title"])

    existing = {t["title"] for t in call("GET", "/admin/tests", token=token)}
    for t in TESTS:
        if t["title"] in existing:
            print("skip test:", t["title"])
            continue
        call("POST", "/admin/tests", {"published": True, **t}, token)
        print("test:", t["title"])

    existing = {s["question"] for s in call("GET", "/admin/scripts", token=token)}
    for s in SCRIPTS:
        if s["question"] in existing:
            print("skip script:", s["question"])
            continue
        call("POST", "/admin/scripts", {"published": True, **s}, token)
        print("script:", s["question"])


if __name__ == "__main__":
    main()
