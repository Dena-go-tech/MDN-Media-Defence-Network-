    token = call("POST", "/auth/login", {"email": email, "password": password})["token"]

    now = datetime.now(timezone.utc)
    existing = {n["title"] for n in call("GET", "/admin/news", token=token)}
    # Oldest first, so ids follow publication order.
    for n in reversed(NEWS):
        if n["title"] in existing:
            print("skip news:", n["title"])
            continue
        item = {k: v for k, v in n.items() if k != "days_ago"}
        item["created_at"] = (now - timedelta(days=n.get("days_ago", 0), hours=len(item["title"]) % 9)).isoformat()
        call("POST", "/admin/news", {"published": True, "featured": False, **item}, token)
        print("news:", n["title"])

    existing = {t["title"] for t in call("GET", "/admin/tests", token=token)}
    for t in TESTS:
        if t["title"] in existing:
            print("skip test:", t["title"])
            continue
        call("POST", "/admin/tests", {"published": True, **t}, token)
        print("test:", t["title"])

