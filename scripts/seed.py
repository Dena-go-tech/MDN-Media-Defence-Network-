#!/usr/bin/env python3
"""Fill the platform with demo news, tests and assistant answers through the admin API.

Usage:
    python3 scripts/seed.py [BASE_URL]

BASE_URL defaults to http://localhost:8080. Admin credentials are read from
ADMIN_EMAIL / ADMIN_PASSWORD (environment or the project's .env file).
Items whose title already exists are skipped, so the script is safe to rerun.
"""
import json
import os
import sys
import urllib.request
from pathlib import Path

BASE = (sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8080").rstrip("/") + "/api"


def load_env():
    env = {}
    path = Path(__file__).resolve().parent.parent / ".env"
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    env.update({k: v for k, v in os.environ.items() if k.startswith("ADMIN_")})
    return env


def call(method, path, body=None, token=None):
    req = urllib.request.Request(BASE + path, method=method, data=json.dumps(body).encode() if body else None)
    req.add_header("Content-Type", "application/json")
    req.add_header("User-Agent", "mdn-seed/1.0")  # Cloudflare blocks the default Python-urllib UA
    if token:
        req.add_header("Authorization", "Bearer " + token)
    with urllib.request.urlopen(req) as res:
        return json.loads(res.read() or "null")


